#!/bin/bash

set -e

# A POSIX variable
OPTIND=1         # Reset in case getopts has been used previously in the shell.

# Initialize our own variables:
testing=""
BUILDDIR="build/"

while getopts "h?tsb:" opt; do
    case "$opt" in
    h|\?)
        echo "-t is testing mode: will replace all external xrefs in each chapter and turn off the glossary."
        echo "-s is solo mode: will replace all external xrefs in each chapter."
        echo "-b [name] is the build dir"
        exit 0
        ;;
    t)  testing="both"
        ;;
    s)  testing="solo"
        ;;
    b)  BUILDDIR="$OPTARG"
        ;;
    esac
done

shift $((OPTIND-1))

[ "$1" = "--" ] && shift

echo "Arg Leftovers: $@"

# Build the merged book in a temp file and move it into place only when
# complete, so a failed merge can never leave a truncated cll.xml that a
# later make run trusts as up to date.
finalfile="$BUILDDIR/cll.xml"
ofile="$BUILDDIR/cll.xml.tmp"
trap 'rm -f "$ofile"' EXIT

cp scripts/header.xml "$ofile"

read_var() {
    ruby scripts/branding-value.rb "$1" "$2"
}

version=$(scripts/build-version.sh) || exit 1
version=$(printf '%s' "$version" | ruby -rcgi -e 'print CGI.escapeHTML(STDIN.read)')
publisher=$(read_var PUBLISHER .env) || exit 1
publisher_disclaimer=$(read_var PUBLISHER_DISCLAIMER .env) || exit 1
title=$(read_var TITLE .env) || exit 1
reviser=$(read_var REVISER .env) || exit 1
subtitle=$(read_var SUBTITL .env) || exit 1
datestamp=$(date +%Y-%m-%d)

subtitle_elem=""
publisher_disclaimer_elem=""
if [ -n "$publisher_disclaimer" ]; then
    publisher_disclaimer_elem="<phrase role=\"publication-disclaimer\">$publisher_disclaimer</phrase>"
fi
if [ -n "$subtitle" ]; then
    subtitle_elem="<subtitle>$subtitle</subtitle>"
fi

echo "

<info>
<title>$title</title>
$subtitle_elem
<author>
<personname>
<firstname>John</firstname>
<othername>Woldemar</othername>
<surname>Cowan</surname>
</personname>
</author>
<othercredit>
<orgname>
revised by $reviser
</orgname>
</othercredit>
<releaseinfo>
<phrase role=\"release-version\">$version</phrase><phrase role=\"release-separator\"> │ </phrase><phrase role=\"release-date\">$datestamp</phrase>
</releaseinfo>
<othercredit>
<orgname role=\"publication-notice\">
$publisher
$publisher_disclaimer_elem
</orgname>
</othercredit>
</info>

<!-- THIS FILE IS AUTOGENERATED.  DO NOT EDIT OR CHECK IN! -->

" >>"$ofile"

for file in "$@"
do
  cat "$file" >>"$ofile"
done

cp "$ofile" "$BUILDDIR/cll_preglossary.xml"

echo '</book>' >>"$BUILDDIR/cll_preglossary.xml"

if [ "$testing" -a "$testing" != "solo" ]
then
  if ! scripts/generate_glossary.rb -b "$BUILDDIR" -t >>"$ofile"
  then
    echo "Glossary generation failed." >&2
    exit 1
  fi
else
  if ! scripts/generate_glossary.rb -b "$BUILDDIR" >>"$ofile"
  then
    echo "Glossary generation failed." >&2
    exit 1
  fi
fi

#rm cll_preglossary.xml

echo '

<index type="lojban-word">
<title>Lojban Words Index</title>
</index>

<index type="general">
<title>General Index</title>
</index>

</book>' >>"$ofile"

if [ "$testing" ]; then
  ruby scripts/partial-references.rb "$ofile"
fi

mv "$ofile" "$finalfile" || exit 1
trap - EXIT
